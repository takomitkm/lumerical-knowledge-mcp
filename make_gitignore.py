"""Regenerate .gitignore with TRUE inverse selection: per-directory deny-all + whitelist.

Pattern:
  <dir>/*          (deny everything in that dir)
  !<dir>/file      (whitelist exact tracked files, recursively)
Only files that exist in the tree at generation time AND are not excluded are whitelisted.
New files created later are IGNORED until the whitelist is regenerated — that is the point.
"""
import os

BASE = os.path.dirname(os.path.abspath(__file__))
EXCLUDE_EXT = {".db", ".db-wal", ".db-shm", ".log", ".pyc", ".fsp", ".html"}
EXCLUDE_DIRNAMES = {"__pycache__", ".pytest_cache", "data", "backups", "corpus",
                    "v241-recipes", "archive", ".git"}
# top-level entries NOT whitelisted even if present
EXCLUDE_TOP = {"corpus", "v241-recipes", "archive", ".tmp", ".git"}


def main():
    lines = [
        "# AUTO-GENERATED by make_gitignore.py — TRUE inverse selection.",
        "# Every directory is deny-all (*); tracked files are whitelisted by exact path.",
        "# New/unlisted files are IGNORED until you regenerate:  python make_gitignore.py",
        "",
        "/*",
        "",
    ]
    # collect whitelist file paths (relative, posix)
    whitelist = []
    for dp, dn, fn in os.walk(BASE):
        dn[:] = [d for d in dn if d not in EXCLUDE_DIRNAMES and not d.startswith(".")]
        for f in sorted(fn):
            if os.path.splitext(f)[1] in EXCLUDE_EXT:
                continue
            rel = os.path.relpath(os.path.join(dp, f), BASE).replace("\\", "/")
            whitelist.append(rel)

    # deny-all per directory, then re-include the directories on each whitelist path.
    # git ignores a file if any PARENT DIRECTORY is excluded, so every directory on the
    # path must be re-included ("!dir/") before the exact file whitelist can take effect.
    dirs = set()
    for rel in whitelist:
        parts = rel.split("/")
        for i in range(1, len(parts)):
            dirs.add("/".join(parts[:i]))
    for d in sorted(dirs):
        lines.append("%s/*" % d)
        lines.append("!/%s/" % d)

    lines.append("")
    lines.append("# ---- whitelisted exact paths ----")
    for rel in sorted(whitelist):
        lines.append("!/%s" % rel)

    # guard: never track junk even if accidentally whitelisted
    lines += [
        "",
        "# ---- hard guards (always ignored, even if whitelisted) ----",
        "**/__pycache__/",
        "**/*.pyc",
        "**/*.db",
        "**/*.db-wal",
        "**/*.db-shm",
        "**/*.log",
        "**/*.fsp",
        "**/.DS_Store",
        "corpus/",
    ]
    open(os.path.join(BASE, ".gitignore"), "w", encoding="utf-8", newline="\n").write(
        "\n".join(lines) + "\n")
    print("wrote .gitignore:", len(whitelist), "whitelisted files,", len(dirs), "deny-all dirs")


if __name__ == "__main__":
    main()


